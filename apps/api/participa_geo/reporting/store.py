"""Atomic report artifact store with a bounded, process-local export limiter.

Generated files live under a git-ignored directory. Each artifact is written to a
temporary file in the same directory and moved into place with ``os.replace``;
there is never a partially written file exposed by the API. The cache key covers
the kind, filters, dataset versions, model run, scenario hashes and the report
rules version, so changing an assumption produces a new artifact.

The limiter is intentionally process-local (one active export per client and ten
new exports per minute), matching the single-worker MVP. Cache hits do not spend
the creation budget.
"""

from __future__ import annotations

import hashlib
import json
import math
import os
import threading
import time
from collections import OrderedDict, deque
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from datetime import UTC, datetime
from pathlib import Path
from uuid import NAMESPACE_URL, UUID, uuid4, uuid5

from participa_geo.api.schemas.reports import (
    FORMAT_BY_KIND,
    INSTITUTIONAL_KINDS,
    ReportArtifactDTO,
    ReportRequest,
)

DEFAULT_QUOTA_BYTES = 1024 * 1024 * 1024  # 1 GiB of generated data
DEFAULT_MAX_ARTIFACT_BYTES = 20 * 1024 * 1024  # 20 MiB per small export
INDEX_VERSION = 1


class ReportStoreError(RuntimeError):
    """Base class for report-store failures."""


class ExportLimitError(ReportStoreError):
    """Raised when a client has an active export or exceeded its budget."""

    def __init__(self, retry_after_seconds: int = 1, *, active: bool = False):
        super().__init__("Límite de exportaciones excedido.")
        self.retry_after_seconds = max(1, int(retry_after_seconds))
        self.active = active


class ReportQuotaError(ReportStoreError):
    """Raised when generated artifacts would exceed the configured quota."""


class InstitutionalPackageNotGenerated(ReportStoreError):
    """Raised when institutional PDFs/ZIP have not been generated by the CLI."""


class _ExportLimiter:
    """Bounded sliding-window limiter with one active request per client."""

    def __init__(
        self,
        *,
        limit: int = 10,
        window_seconds: float = 60.0,
        max_clients: int = 512,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self.limit = max(1, limit)
        self.window_seconds = float(window_seconds)
        self.max_clients = max(1, max_clients)
        self._clock = clock
        self._events: OrderedDict[str, deque[float]] = OrderedDict()
        self._active: set[str] = set()
        self._lock = threading.Lock()

    @property
    def tracked_clients(self) -> int:
        with self._lock:
            return len(self._events)

    def _prune(self, now: float) -> None:
        cutoff = now - self.window_seconds
        for key in list(self._events):
            events = self._events[key]
            while events and events[0] <= cutoff:
                events.popleft()
            if not events:
                del self._events[key]

    def _make_room(self) -> None:
        while len(self._events) >= self.max_clients:
            victim = next(
                (key for key in self._events if key not in self._active), None
            )
            if victim is None:
                raise ExportLimitError(active=True)
            del self._events[victim]

    @contextmanager
    def acquire(self, client_key: str) -> Iterator[None]:
        now = self._clock()
        with self._lock:
            if client_key in self._active:
                raise ExportLimitError(active=True)
            self._prune(now)
            events = self._events.get(client_key)
            if events is None:
                self._make_room()
                events = deque()
                self._events[client_key] = events
            else:
                self._events.move_to_end(client_key)
            if len(events) >= self.limit:
                retry_after = math.ceil(events[0] + self.window_seconds - now)
                raise ExportLimitError(retry_after_seconds=retry_after)
            events.append(now)
            self._active.add(client_key)
        try:
            yield
        finally:
            with self._lock:
                self._active.discard(client_key)


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _utc_now() -> datetime:
    return datetime.now(UTC)


class ReportStore:
    """Filesystem-backed artifact store with an in-process limiter."""

    def __init__(
        self,
        root: Path | str,
        *,
        institutional_dir: Path | str | None = None,
        quota_bytes: int = DEFAULT_QUOTA_BYTES,
        max_artifact_bytes: int = DEFAULT_MAX_ARTIFACT_BYTES,
        limit: int = 10,
        window_seconds: float = 60.0,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self.root = Path(root)
        self.institutional_dir = Path(
            institutional_dir if institutional_dir is not None else self.root / "institutional"
        )
        self.quota_bytes = quota_bytes
        self.max_artifact_bytes = max_artifact_bytes
        self.root.mkdir(parents=True, exist_ok=True)
        self.institutional_dir.mkdir(parents=True, exist_ok=True)
        self._index_path = self.root / "index.json"
        self._manifest_path = self.institutional_dir / "manifest.json"
        self._limiter = _ExportLimiter(
            limit=limit, window_seconds=window_seconds, clock=clock
        )
        self._lock = threading.RLock()

    # -- public API -------------------------------------------------------

    def get_or_create(
        self,
        request: ReportRequest,
        *,
        builder: Callable[[], bytes],
        filename: str,
        media_type: str,
        sources: dict,
        cache_key: str,
        client_key: str,
        model_run_id: UUID | None = None,
        scenario_id: UUID | None = None,
    ) -> ReportArtifactDTO:
        """Return a cached artifact or generate it atomically and cache it."""
        kind = str(request.kind)
        if kind in INSTITUTIONAL_KINDS:
            return self._get_institutional(kind, cached=True)

        report_id = self._artifact_id(kind, cache_key)
        cached = self._cached_entry(report_id)
        if cached is not None:
            return self._to_dto(cached, cached=True)

        with self._limiter.acquire(client_key):
            cached = self._cached_entry(report_id)
            if cached is not None:
                return self._to_dto(cached, cached=True)

            data = builder()
            if not isinstance(data, (bytes, bytearray)) or not data:
                raise ReportStoreError("el generador no produjo contenido")
            payload = bytes(data)
            if len(payload) > self.max_artifact_bytes:
                raise ReportStoreError(
                    "el archivo excede el límite de 20 MiB para exportaciones pequeñas"
                )

            fmt = FORMAT_BY_KIND[kind]
            storage_name = f"{report_id}.{fmt}"
            target = self.root / storage_name
            self._write_atomic(target, payload)

            with self._lock:
                index = self._load_index()
                projected = sum(
                    int(entry.get("size_bytes", 0))
                    for entry in index["entries"].values()
                ) + len(payload)
                if projected > self.quota_bytes:
                    target.unlink(missing_ok=True)
                    raise ReportQuotaError(
                        "la cuota de 1 GiB de datos generados está agotada"
                    )
                created_at = _utc_now()
                entry = {
                    "report_id": str(report_id),
                    "kind": kind,
                    "format": fmt,
                    "status": "ready",
                    "size_bytes": len(payload),
                    "sha256": _sha256(payload),
                    "created_at": created_at.isoformat(),
                    "filename": Path(filename).name or f"participa-geo-{report_id}.{fmt}",
                    "storage_name": storage_name,
                    "media_type": media_type,
                    "sources": sources,
                    "model_run_id": str(model_run_id) if model_run_id else None,
                    "scenario_id": str(scenario_id) if scenario_id else None,
                }
                index["entries"][str(report_id)] = entry
                try:
                    self._save_index(index)
                except BaseException:
                    target.unlink(missing_ok=True)
                    raise
            return self._to_dto(entry, cached=False)

    def publish_institutional(
        self,
        kind: str,
        data: bytes,
        *,
        filename: str,
        media_type: str,
        sources: dict,
        model_run_id: UUID | None = None,
        scenario_id: UUID | None = None,
    ) -> ReportArtifactDTO:
        """Publish a CLI-generated institutional artifact + manifest entry."""
        if kind not in INSTITUTIONAL_KINDS:
            raise ValueError(f"kind institucional desconocido: {kind}")
        payload = bytes(data)
        if not payload:
            raise ReportStoreError("el artefacto institucional está vacío")
        digest = _sha256(payload)
        report_id = uuid5(NAMESPACE_URL, f"participa-geo:institutional:{kind}:{digest}")
        safe_name = Path(filename).name

        with self._lock:
            manifest = self._load_manifest()
            index = self._load_index()
            current = sum(
                int(entry.get("size_bytes", 0))
                for entry in list(index["entries"].values())
                + [value for key, value in manifest["entries"].items() if key != kind]
            )
            if current + len(payload) > self.quota_bytes:
                raise ReportQuotaError(
                    "la cuota de 1 GiB de datos generados está agotada"
                )
            target = self.institutional_dir / safe_name
            self._write_atomic(target, payload)
            created_at = _utc_now().isoformat()
            manifest["entries"][kind] = {
                "report_id": str(report_id),
                "kind": kind,
                "format": FORMAT_BY_KIND[kind],
                "status": "ready",
                "size_bytes": len(payload),
                "sha256": digest,
                "created_at": created_at,
                "filename": safe_name,
                "storage_name": safe_name,
                "media_type": media_type,
                "sources": sources,
                "model_run_id": str(model_run_id) if model_run_id else None,
                "scenario_id": str(scenario_id) if scenario_id else None,
            }
            manifest["updated_at"] = created_at
            self._save_manifest(manifest)
        return self._to_dto(manifest["entries"][kind], cached=False)

    def list(self, *, limit: int = 50) -> list[ReportArtifactDTO]:
        """Return generated artifacts, newest first (dynamic + institutional)."""
        entries: dict[str, dict] = {}
        with self._lock:
            for entry in self._load_index()["entries"].values():
                entries[str(entry["report_id"])] = entry
            for entry in self._load_manifest()["entries"].values():
                entries[str(entry["report_id"])] = entry
        ordered = sorted(
            entries.values(), key=lambda item: item.get("created_at", ""), reverse=True
        )
        return [self._to_dto(entry, cached=True) for entry in ordered[: max(0, limit)]]

    def get(self, report_id: UUID) -> ReportArtifactDTO | None:
        entry = self._find_entry(report_id)
        if entry is None:
            return None
        return self._to_dto(entry, cached=True)

    def path_for(self, report_id: UUID) -> Path | None:
        entry = self._find_entry(report_id)
        if entry is None or entry.get("status") != "ready":
            return None
        base = (
            self.institutional_dir
            if entry["kind"] in INSTITUTIONAL_KINDS
            else self.root
        )
        path = base / str(entry.get("storage_name") or entry.get("filename") or "")
        return path if path.is_file() else None

    # -- internals --------------------------------------------------------

    @staticmethod
    def _artifact_id(kind: str, cache_key: str) -> UUID:
        return uuid5(NAMESPACE_URL, f"participa-geo:report:{kind}:{cache_key}")

    def _find_entry(self, report_id: UUID) -> dict | None:
        with self._lock:
            entry = self._load_index()["entries"].get(str(report_id))
            if entry is not None:
                return entry
            for candidate in self._load_manifest()["entries"].values():
                if str(candidate.get("report_id")) == str(report_id):
                    return candidate
            return None

    def _cached_entry(self, report_id: UUID) -> dict | None:
        entry = self._find_entry(report_id)
        if entry is None or entry.get("status") != "ready":
            return None
        path = self.path_for(report_id)
        if path is None:
            return None
        if path.stat().st_size != int(entry.get("size_bytes", -1)):
            return None
        return entry

    def _get_institutional(self, kind: str, *, cached: bool) -> ReportArtifactDTO:
        with self._lock:
            manifest = self._load_manifest()
            entry = manifest["entries"].get(kind)
        if entry is None or entry.get("status") != "ready":
            raise InstitutionalPackageNotGenerated(
                "El paquete institucional no ha sido generado por la CLI."
            )
        path = self.institutional_dir / str(
            entry.get("storage_name") or entry.get("filename", "")
        )
        if not path.is_file():
            raise InstitutionalPackageNotGenerated(
                "El artefacto institucional no está disponible en disco."
            )
        if path.stat().st_size != int(entry.get("size_bytes", -1)):
            raise InstitutionalPackageNotGenerated(
                "El artefacto institucional no coincide con su manifiesto."
            )
        return self._to_dto(entry, cached=cached)

    def _to_dto(self, entry: dict, *, cached: bool) -> ReportArtifactDTO:
        created_at = entry.get("created_at")
        if isinstance(created_at, str):
            created_at = datetime.fromisoformat(created_at)
        if not isinstance(created_at, datetime):
            created_at = _utc_now()
        report_id = UUID(str(entry["report_id"]))
        return ReportArtifactDTO(
            report_id=report_id,
            kind=entry["kind"],
            format=entry["format"],
            status=entry["status"],
            size_bytes=int(entry.get("size_bytes", 0)),
            sha256=str(entry.get("sha256", "")),
            created_at=created_at,
            download_url=f"/api/v1/reports/{report_id}/download",
            filename=str(entry.get("filename", "")),
            cached=cached,
            scenario_id=(
                UUID(str(entry["scenario_id"])) if entry.get("scenario_id") else None
            ),
            model_run_id=(
                UUID(str(entry["model_run_id"])) if entry.get("model_run_id") else None
            ),
            sources=entry.get("sources") or {},
        )

    def _empty_index(self) -> dict:
        return {"version": INDEX_VERSION, "entries": {}}

    def _load_index(self) -> dict:
        if not self._index_path.is_file():
            return self._empty_index()
        try:
            data = json.loads(self._index_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise ReportStoreError("el índice de reportes está corrupto") from exc
        if not isinstance(data, dict) or not isinstance(data.get("entries"), dict):
            raise ReportStoreError("el índice de reportes tiene un formato inválido")
        return data

    def _save_index(self, index: dict) -> None:
        self._write_atomic(
            self._index_path,
            (json.dumps(index, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode(
                "utf-8"
            ),
        )

    def _empty_manifest(self) -> dict:
        return {
            "version": INDEX_VERSION,
            "team_slug": "participa-geo",
            "entries": {},
            "updated_at": None,
        }

    def _load_manifest(self) -> dict:
        if not self._manifest_path.is_file():
            return self._empty_manifest()
        try:
            data = json.loads(self._manifest_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise ReportStoreError("el manifiesto institucional está corrupto") from exc
        if not isinstance(data, dict) or not isinstance(data.get("entries"), dict):
            raise ReportStoreError("el manifiesto institucional tiene un formato inválido")
        return data

    def _save_manifest(self, manifest: dict) -> None:
        self._write_atomic(
            self._manifest_path,
            (
                json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
            ).encode("utf-8"),
        )

    @staticmethod
    def _write_atomic(path: Path, payload: bytes) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.parent / f".tmp-{uuid4().hex}"
        try:
            with temporary.open("wb") as handle:
                handle.write(payload)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)


